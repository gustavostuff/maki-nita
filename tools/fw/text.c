static const uint8_t dot[TEXT_H] = {0x00, 0x00, 0x00, 0x00, 0x02};
static const uint8_t dash[TEXT_H] = {0x00, 0x00, 0x0e, 0x00, 0x00};
static const uint8_t colon[TEXT_H] = {0x00, 0x02, 0x00, 0x02, 0x00};
static const uint8_t blank[TEXT_H] = {0x00, 0x00, 0x00, 0x00, 0x00};

static const uint8_t *glyph(char c)
{
    if (c >= '0' && c <= '9')
        return digits[c - '0'];
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z')
        return letters[c - 'A'];
    if (c == '.')
        return dot;
    if (c == '-')
        return dash;
    if (c == ':')
        return colon;
    if (c == ' ')
        return blank;
    return 0;
}

static void blit(int x, int y, const uint8_t *rows)
{
    int row;
    int col;

    for (row = 0; row < TEXT_H; row++) {
        for (col = 0; col < TEXT_W; col++) {
            int px;
            int py;

            if ((rows[row] & (uint8_t)(1u << col)) == 0)
                continue;
            px = x + col;
            py = y + row;
            if (px < 0 || py < 0)
                continue;
            pixel((uint8_t)px, (uint8_t)py, true);
        }
    }
}

void text_draw(int x, int y, const char *s)
{
    if (s == 0)
        return;
    for (; *s != '\0'; s++) {
        const uint8_t *rows = glyph(*s);

        if (rows == 0)
            continue;
        blit(x, y, rows);
        x += TEXT_W;
    }
}
